"use strict";

let wordSaveSequence = 0;

function wordStyleOf(node, inherited) {
  const style = {...inherited};
  const {tagName, style: css} = node;
  if (tagName === "B" || tagName === "STRONG") style.bold = true;
  if (tagName === "I" || tagName === "EM") style.italic = true;
  if (tagName === "U") style.underline = true;
  if (tagName === "S" || tagName === "STRIKE" || tagName === "DEL") style.strike = true;
  if (tagName === "FONT") {
    if (node.hasAttribute("face")) style.font = wordFont(node.getAttribute("face"));
    if (node.hasAttribute("size")) style.size = [8, 10, 11, 14, 18, 24, 36][Number(node.getAttribute("size")) - 1] || 11;
  }
  if (/^H[1-3]$/.test(tagName)) {
    style.bold = true;
    style.size = [22, 17, 14][Number(tagName[1]) - 1];
  }
  if (css.fontFamily) style.font = wordFont(css.fontFamily);
  if (css.fontSize) {
    const amount = Number.parseFloat(css.fontSize);
    if (css.fontSize.endsWith("pt")) style.size = wordSize(amount);
    if (css.fontSize.endsWith("px")) style.size = wordSize(amount * 0.75);
  }
  if (css.fontWeight) style.bold = css.fontWeight === "bold" || Number(css.fontWeight) >= 600;
  if (css.fontStyle) style.italic = css.fontStyle === "italic";
  if (css.textDecorationLine) {
    style.underline = css.textDecorationLine.includes("underline");
    style.strike = css.textDecorationLine.includes("line-through");
  }
  return style;
}

function wordAlignment(node) {
  const raw = node.getAttribute("style") || "";
  const value = node.style.textAlign || node.getAttribute("align") ||
    /(?:^|;)\s*text-align\s*:\s*(left|center|right|justify)\s*(?:;|$)/i.exec(raw)?.[1];
  return ["left", "center", "right", "justify"].includes(value) ? value : "";
}

// WebView may block style attributes generated by editing commands. Reapply only the supported properties through CSSOM.
function restoreWordStyles(editor) {
  for (const node of editor.querySelectorAll("[style]")) {
    const raw = node.getAttribute("style") || "";
    const properties = new Map([...raw.matchAll(/(?:^|;)\s*([a-z-]+)\s*:\s*([^;]+)/gi)]
      .map(([, key, value]) => [key.toLowerCase(), value.trim()]));
    const align = wordAlignment(node);
    if (align && !node.style.textAlign) node.style.textAlign = align;
    const font = properties.get("font-family");
    if (font && !node.style.fontFamily) node.style.fontFamily = wordFontNames[wordFont(font)];
    const size = properties.get("font-size");
    if (size && /^(?:\d+|\d+\.\d+)(?:px|pt)$/.test(size) && !node.style.fontSize) {
      node.style.fontSize = wordSize(Number.parseFloat(size) * (size.endsWith("px") ? 0.75 : 1)) + "pt";
    }
    const weight = properties.get("font-weight");
    if (weight && /^(normal|bold|[1-9]00)$/.test(weight) && !node.style.fontWeight) node.style.fontWeight = weight;
    const italic = properties.get("font-style");
    if (italic && /^(normal|italic)$/.test(italic) && !node.style.fontStyle) node.style.fontStyle = italic;
    const decoration = properties.get("text-decoration-line") || properties.get("text-decoration");
    if (decoration && /^(?:none|underline|line-through|underline line-through|line-through underline)$/.test(decoration)
        && !node.style.textDecorationLine) node.style.textDecorationLine = decoration;
  }
}

function readWordEditor(editor) {
  const result = [];
  let current = null;
  let chars = 0;

  function append(text, style, kind, align) {
    if (!current) current = wordParagraph(kind, align);
    const safe = text.replace(/\u0000/g, "");
    if (!safe) return;
    chars += safe.length;
    if (chars > wordLimit) throw Error("This document exceeds WordPad’s text limit.");
    const last = current.runs.at(-1);
    if (last && wordSameStyle(last, style)) last.text += safe;
    else current.runs.push({...style, text: safe});
  }

  function flush() {
    if (!current) return;
    result.push(current);
    current = null;
    if (result.length > 7000) throw Error("This document has too many paragraphs.");
  }

  function visit(node, inherited, kind, align) {
    if (node.nodeType === Node.TEXT_NODE) {
      append(node.data, inherited, kind, align);
      return;
    }
    if (node.nodeType !== Node.ELEMENT_NODE) return;
    const tag = node.tagName;
    if (!["DIV", "P", "H1", "H2", "H3", "LI", "OL", "UL", "SPAN", "FONT",
      "B", "STRONG", "I", "EM", "U", "S", "STRIKE", "DEL", "BR", "BLOCKQUOTE"].includes(tag)) return;
    if (tag === "BR") {
      if (node.parentNode?.childNodes.length > 1) append("\n", inherited, kind, align);
      return;
    }
    const style = wordStyleOf(node, inherited);
    const nextAlign = wordAlignment(node) || align;
    if (tag === "OL" || tag === "UL") {
      flush();
      for (const child of node.children) visit(child, style, tag.toLowerCase(), nextAlign);
      return;
    }
    const block = ["DIV", "P", "H1", "H2", "H3", "LI", "BLOCKQUOTE"].includes(tag);
    if (block) {
      flush();
      if (/^H[1-3]$/.test(tag)) kind = tag.toLowerCase();
      if (tag === "LI" && kind === "p") kind = "ul";
      current = wordParagraph(kind, nextAlign);
    }
    for (const child of node.childNodes) visit(child, style, kind, nextAlign);
    if (block) flush();
  }

  for (const node of editor.childNodes) visit(node, wordNormalStyle, "p", "left");
  flush();
  return result.length ? result : [wordParagraph()];
}

function drawWordEditor(editor, paragraphs) {
  const fragment = document.createDocumentFragment();
  let list = null;
  for (const paragraph of paragraphs) {
    const isList = paragraph.kind === "ul" || paragraph.kind === "ol";
    const block = element(isList ? "li" : paragraph.kind);
    block.style.textAlign = paragraph.align;
    for (const run of paragraph.runs) {
      const span = element("span", "", run.text);
      span.style.fontFamily = wordFontNames[run.font] || wordFontNames[0];
      span.style.fontSize = wordSize(run.size) + "pt";
      span.style.fontWeight = run.bold ? "bold" : "normal";
      span.style.fontStyle = run.italic ? "italic" : "normal";
      if (run.underline || run.strike) {
        span.style.textDecorationLine = [run.underline ? "underline" : "", run.strike ? "line-through" : ""].filter(Boolean).join(" ");
      }
      block.append(span);
    }
    if (!block.hasChildNodes()) block.append(element("br"));
    if (isList) {
      if (list?.tagName.toLowerCase() !== paragraph.kind) {
        list = element(paragraph.kind);
        fragment.append(list);
      }
      list.append(block);
    } else {
      list = null;
      fragment.append(block);
    }
  }
  editor.replaceChildren(fragment);
}

function renderWordPad(win) {
  const panel = element("div", "wordpad");
  const files = element("div", "app-toolbar");
  const ribbon = element("div", "app-toolbar word-tools");
  const editor = element("div", "word-editor");
  editor.contentEditable = "true";
  editor.setAttribute("role", "textbox");
  editor.setAttribute("aria-label", "WordPad document");
  editor.setAttribute("aria-multiline", "true");
  editor.spellcheck = true;
  const status = appStatus("Untitled");
  let range = null;
  let dirty = false;
  let timer = 0;
  let name = "Untitled.rtf";
  let revision = 0;
  let pending = "";

  function setStatus(message = "") {
    const text = editor.innerText.trim();
    const count = text ? text.split(/\s+/).length : 0;
    status.textContent = message || name + (dirty ? " · Unsaved" : "") + " · " + count + (count === 1 ? " word" : " words");
  }

  function snapshot() {
    const rtf = writeWordRtf(readWordEditor(editor));
    if (rtf.length > 780000) throw Error("This document exceeds WordPad’s formatting limit.");
    return rtf;
  }

  function persist(rtf) {
    clearTimeout(timer);
    try {
      const data = JSON.stringify({rtf: rtf || snapshot(), name, dirty});
      if (native?.saveWordDraft) native.saveWordDraft(data);
      else localStorage.setItem("retro-wordpad", data);
    } catch (error) {
      setStatus(error.message);
    }
  }

  function changed() {
    revision++;
    dirty = true;
    setStatus();
    clearTimeout(timer);
    timer = setTimeout(persist, 300);
  }

  function load(rows, fileName, unsaved) {
    range = null;
    drawWordEditor(editor, rows);
    name = fileName || "Untitled.rtf";
    dirty = !!unsaved;
    revision++;
    setStatus();
    persist();
    editor.scrollTop = 0;
  }

  function keepRange() {
    const selection = window.getSelection();
    if (!selection?.rangeCount) return;
    const next = selection.getRangeAt(0);
    if (editor.contains(next.startContainer) && editor.contains(next.endContainer)) range = next.cloneRange();
  }

  function selectedBlocks() {
    const selection = window.getSelection();
    if (!selection?.rangeCount) return [];
    const selected = selection.getRangeAt(0);
    const types = "p,div,h1,h2,h3,li,blockquote";
    return [...editor.querySelectorAll(types)].filter(node => !node.querySelector(types) && selected.intersectsNode(node));
  }

  function format(command, value) {
    editor.focus();
    if (range && editor.contains(range.startContainer)) {
      const selection = window.getSelection();
      selection.removeAllRanges();
      selection.addRange(range);
    }
    const alignments = command === "formatBlock" ? selectedBlocks().map(wordAlignment) : [];
    if (document.execCommand(command, false, value)) {
      restoreWordStyles(editor);
      if (alignments.some(Boolean)) {
        const blocks = selectedBlocks();
        if (blocks.length === alignments.length) {
          blocks.forEach((block, index) => { if (alignments[index]) block.style.textAlign = alignments[index]; });
        }
      }
      keepRange();
      changed();
    }
  }

  function newDocument(action, message) {
    if (!dirty) { action(); return; }
    dialog({kind: "word-replace", title: "WordPad", icon: "wordpad",
      message, accept: "Discard Changes", cancel: "Cancel", onAccept: action});
  }

  function save() {
    if (!native?.desktopFile) { setStatus("The workspace is available in the Android launcher."); return; }
    if (pending) return;
    try {
      const rtf = snapshot();
      const requestedRevision = revision;
      const suggestedName = name.replace(/\.(txt|rtf)$/i, "") + ".rtf";
      pending = "wordpad:" + (++wordSaveSequence);
      saveAs.disabled = true;
      win.finishWordSave = result => {
        if (result.id !== pending) return;
        pending = "";
        saveAs.disabled = false;
        if (result.ok && revision === requestedRevision) {
          name = result.name || suggestedName;
          dirty = false;
          persist(rtf);
        }
        setStatus(result.message || "");
      };
      setStatus("Saving to My Documents…");
      native.desktopFile("save-wordpad", pending, JSON.stringify({name: suggestedName, rtf}));
    } catch (error) {
      pending = "";
      saveAs.disabled = false;
      setStatus(error.message);
    }
  }

  const newFile = toolbarButton("New", () => newDocument(
    () => load([wordParagraph()], "Untitled.rtf", false), "Start a new document and discard changes to the current one?"));
  const open = toolbarButton("Open…", () => openFileLocation("documents"));
  const importFile = toolbarButton("Import…", () => native?.desktopFile?.("open-wordpad", "", ""));
  const saveAs = toolbarButton("Save RTF", save);
  files.append(newFile, open, saveAs, importFile);

  const families = element("select", "text-entry");
  families.setAttribute("aria-label", "Font");
  families.add(new Option("Font", ""));
  wordFontNames.forEach(font => families.add(new Option(font, font)));
  families.addEventListener("change", () => { if (families.value) format("fontName", families.value); });
  const sizes = element("select", "text-entry");
  sizes.setAttribute("aria-label", "Font size");
  sizes.add(new Option("Size", ""));
  [8, 10, 11, 14, 18, 24, 36].forEach((size, index) => sizes.add(new Option(String(size), String(index + 1))));
  sizes.addEventListener("change", () => { if (sizes.value) format("fontSize", sizes.value); });
  const blocks = element("select", "text-entry");
  blocks.setAttribute("aria-label", "Paragraph style");
  blocks.append(new Option("Style", ""), new Option("Normal", "p"), new Option("Heading 1", "h1"),
    new Option("Heading 2", "h2"), new Option("Heading 3", "h3"));
  blocks.addEventListener("change", () => { if (blocks.value) format("formatBlock", blocks.value); });
  ribbon.append(families, sizes, blocks);

  for (const [label, description, command] of [
    ["B", "Bold", "bold"], ["I", "Italic", "italic"], ["U", "Underline", "underline"], ["S", "Strikethrough", "strikeThrough"],
    ["Left", "Align left", "justifyLeft"], ["Center", "Align center", "justifyCenter"], ["Right", "Align right", "justifyRight"],
    ["Bullets", "Bulleted list", "insertUnorderedList"], ["Numbers", "Numbered list", "insertOrderedList"]
  ]) {
    const control = toolbarButton(label, () => format(command));
    control.setAttribute("aria-label", description);
    control.title = description;
    control.addEventListener("pointerdown", event => event.preventDefault());
    ribbon.append(control);
  }

  document.addEventListener("selectionchange", keepRange);
  editor.addEventListener("input", changed);
  editor.addEventListener("beforeinput", event => {
    if (!event.inputType?.startsWith("insert")) return;
    const replacing = window.getSelection()?.toString().length || 0;
    if (editor.textContent.length - replacing + (event.data?.length || 1) > wordLimit) event.preventDefault();
  });
  editor.addEventListener("dragover", event => event.preventDefault());
  editor.addEventListener("drop", event => event.preventDefault());
  editor.addEventListener("paste", event => {
    event.preventDefault();
    const available = wordLimit - editor.textContent.length + (window.getSelection()?.toString().length || 0);
    const text = event.clipboardData?.getData("text/plain")?.slice(0, Math.max(0, available)).replace(/\u0000/g, "");
    if (text) document.execCommand("insertText", false, text);
  });
  win.node.addEventListener("keydown", event => {
    if (!(event.ctrlKey || event.metaKey)) return;
    if (event.key.toLowerCase() === "s") { event.preventDefault(); save(); }
    if (event.key.toLowerCase() === "o") { event.preventDefault(); open.click(); }
  });
  win.openWordDocument = file => {
    try {
      const rows = file.format === "rtf" ? parseWordRtf(file.text) : wordPlainText(file.text);
      newDocument(() => load(rows, file.name, false), "Open another document and discard changes to the current one?");
    } catch (error) {
      setStatus(error.message);
    }
  };
  win.cleanup = () => {
    document.removeEventListener("selectionchange", keepRange);
    persist();
  };
  panel.append(files, ribbon, editor, status);
  win.body.replaceChildren(panel);
  try {
    const saved = JSON.parse(native?.loadWordDraft?.() || localStorage.getItem("retro-wordpad") || "null");
    if (saved?.rtf) load(parseWordRtf(saved.rtf), saved.name, saved.dirty);
    else drawWordEditor(editor, [wordParagraph()]);
  } catch (error) {
    drawWordEditor(editor, [wordParagraph()]);
  }
  setStatus();
}

window.wordDocumentOpened = file => openWindow("wordpad").openWordDocument(file);
